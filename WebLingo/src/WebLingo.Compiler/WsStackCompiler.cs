using WebLingo.Bytecode;
using WebLingo.Core;
namespace WebLingo.Compiler;

public sealed record WsStackCompilationResult(WsStackModule? Module, IReadOnlyList<WsDiagnostic> Diagnostics);

/// <summary>
/// The compiler for the stack VM (specification, section 5.6, "The comparison's parts", part 3): the same front end
/// as <see cref="WsCompiler"/> (<see cref="WsCompilation"/>), so the same diagnostics, then
/// <see cref="WsStackCodeGenerator"/>. What it generates must pass <see cref="WsStackBytecodeVerifier"/>; if it does
/// not, that is the compiler's error, reported as WS4001, and no module is returned.
/// </summary>
public sealed class WsStackCompiler(WsCompilerOptions options)
{
    public WsStackCompilationResult Compile(string source, string sourceName)
    {
        var compilation = WsCompilation.Create(source, sourceName, options);
        if (compilation.HasErrors) return new WsStackCompilationResult(null, compilation.Diagnostics);

        var diagnostics = new List<WsDiagnostic>(compilation.Diagnostics);
        var module = WsStackCodeGenerator.Generate(compilation.LoweredProgram!, sourceName, diagnostics);
        if (module is null) return new WsStackCompilationResult(null, diagnostics);

        var verification = new WsStackBytecodeVerifier().Verify(module);
        if (!verification.IsValid)
        {
            diagnostics.Add(new WsDiagnostic(WsDiagnosticCodes.BytecodeVerificationFailure, WsDiagnosticSeverity.Error,
                $"Internal compiler error: the generated bytecode failed verification: {verification.Error}",
                new WsSourceSpan(0, 0)));
            return new WsStackCompilationResult(null, diagnostics);
        }
        return new WsStackCompilationResult(module, diagnostics);
    }
}
