using WebLingo.Bytecode;
using WebLingo.Core;
using WebLingo.Language;
namespace WebLingo.Compiler;

public sealed record WebLingoCompilationResult(WebLingoCompiledModule? Module, IReadOnlyList<WebLingoDiagnostic> Diagnostics);
public interface IWebLingoCompiler { WebLingoCompilationResult Compile(string source, string sourceName); }

/// <summary>
/// The compiler: a source text through the front end (<see cref="WebLingoCompilation"/>), then the bytecode generator.
/// What it generates must pass the verifier; if it does not, that is the compiler's error, reported as WL4001,
/// and no module is returned.
/// </summary>
public sealed class WebLingoCompiler(WebLingoCompilerOptions options) : IWebLingoCompiler
{
    public WebLingoCompilationResult Compile(string source, string sourceName) =>
        Generate(WebLingoCompilation.Create(source, sourceName, options), sourceName);

    /// <summary>A program whose own file another reader parsed, such as a template compiler (specification, section 13).</summary>
    public WebLingoCompilationResult Compile(WebLingoSyntaxTree syntaxTree) =>
        Generate(WebLingoCompilation.Create(syntaxTree, options), syntaxTree.Source.Name);

    /// <summary>The file <paramref name="name"/>, whose text is <paramref name="source"/>, compiled as an import (section 3.9).</summary>
    public WebLingoCompilationResult CompileImport(string name, string source) =>
        Generate(WebLingoCompilation.CreateImport(name, source, options), "import " + name);

    private WebLingoCompilationResult Generate(WebLingoCompilation compilation, string sourceName)
    {
        if (compilation.HasErrors) return new WebLingoCompilationResult(null, compilation.Diagnostics);

        var diagnostics = new List<WebLingoDiagnostic>(compilation.Diagnostics);
        var module = WebLingoCodeGenerator.Generate(compilation.LoweredProgram!, sourceName, diagnostics);
        if (module is null) return new WebLingoCompilationResult(null, diagnostics);

        var verification = new WebLingoBytecodeVerifier().Verify(module);
        if (!verification.IsValid)
        {
            diagnostics.Add(new WebLingoDiagnostic(WebLingoDiagnosticCodes.BytecodeVerificationFailure, WebLingoDiagnosticSeverity.Error,
                $"Internal compiler error: the generated bytecode failed verification: {verification.Error}",
                new WebLingoSourceSpan(0, 0)));
            return new WebLingoCompilationResult(null, diagnostics);
        }
        return new WebLingoCompilationResult(module, diagnostics);
    }
}
