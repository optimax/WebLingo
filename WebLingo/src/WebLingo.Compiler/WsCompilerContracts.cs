using WebLingo.Bytecode;
using WebLingo.Core;
namespace WebLingo.Compiler;

public sealed record WsCompilationResult(WsCompiledModule? Module, IReadOnlyList<WsDiagnostic> Diagnostics);
public interface IWsCompiler { WsCompilationResult Compile(string source, string sourceName); }

/// <summary>
/// The compiler: a source text through the front end (<see cref="WsCompilation"/>), then the bytecode generator.
/// What it generates must pass the verifier; if it does not, that is the compiler's error, reported as WS4001,
/// and no module is returned.
/// </summary>
public sealed class WsCompiler(WsCompilerOptions options) : IWsCompiler
{
    public WsCompilationResult Compile(string source, string sourceName)
    {
        var compilation = WsCompilation.Create(source, sourceName, options);
        if (compilation.HasErrors) return new WsCompilationResult(null, compilation.Diagnostics);

        var diagnostics = new List<WsDiagnostic>(compilation.Diagnostics);
        var module = WsCodeGenerator.Generate(compilation.LoweredProgram!, sourceName, diagnostics);
        if (module is null) return new WsCompilationResult(null, diagnostics);

        var verification = new WsBytecodeVerifier().Verify(module);
        if (!verification.IsValid)
        {
            diagnostics.Add(new WsDiagnostic(WsDiagnosticCodes.BytecodeVerificationFailure, WsDiagnosticSeverity.Error,
                $"Internal compiler error: the generated bytecode failed verification: {verification.Error}",
                new WsSourceSpan(0, 0)));
            return new WsCompilationResult(null, diagnostics);
        }
        return new WsCompilationResult(module, diagnostics);
    }
}
