using WebLingo.Bytecode;
using WebLingo.Core;
namespace WebLingo.Compiler;

public sealed record WebLingoStackCompilationResult(WebLingoStackModule? Module, IReadOnlyList<WebLingoDiagnostic> Diagnostics);

/// <summary>
/// The compiler for the stack VM (specification, section 5.6, "The comparison's parts", part 3): the same front end
/// as <see cref="WebLingoCompiler"/> (<see cref="WebLingoCompilation"/>), so the same diagnostics, then
/// <see cref="WebLingoStackCodeGenerator"/>. What it generates must pass <see cref="WebLingoStackBytecodeVerifier"/>; if it does
/// not, that is the compiler's error, reported as WL4001, and no module is returned.
/// </summary>
public sealed class WebLingoStackCompiler(WebLingoCompilerOptions options)
{
    public WebLingoStackCompilationResult Compile(string source, string sourceName)
    {
        var compilation = WebLingoCompilation.Create(source, sourceName, options);
        if (compilation.HasErrors) return new WebLingoStackCompilationResult(null, compilation.Diagnostics);

        var diagnostics = new List<WebLingoDiagnostic>(compilation.Diagnostics);
        var module = WebLingoStackCodeGenerator.Generate(compilation.LoweredProgram!, sourceName, diagnostics);
        if (module is null) return new WebLingoStackCompilationResult(null, diagnostics);

        var verification = new WebLingoStackBytecodeVerifier().Verify(module);
        if (!verification.IsValid)
        {
            diagnostics.Add(new WebLingoDiagnostic(WebLingoDiagnosticCodes.BytecodeVerificationFailure, WebLingoDiagnosticSeverity.Error,
                $"Internal compiler error: the generated bytecode failed verification: {verification.Error}",
                new WebLingoSourceSpan(0, 0)));
            return new WebLingoStackCompilationResult(null, diagnostics);
        }
        return new WebLingoStackCompilationResult(module, diagnostics);
    }
}
